const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const test = require('node:test')
const { AlarmToneService } = require('./alarm-tone-service.cjs')

test('stores a validated personal ringtone under its managed directory', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'mydesk-alarm-tone-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const source = path.join(directory, 'warm.wav')
  const bytes = Buffer.alloc(44)
  bytes.write('RIFF', 0)
  bytes.write('WAVE', 8)
  await fs.writeFile(source, bytes)

  const service = new AlarmToneService(path.join(directory, 'managed'))
  const tone = await service.store(source)
  assert.equal(tone.type, 'custom')
  assert.equal(tone.name, 'warm.wav')
  assert.match(tone.id, /^[0-9a-f-]{36}$/i)
  assert.match(await service.dataUrl(tone.id, tone.extension), /^data:audio\/wav;base64,/)
  await service.remove(tone.id, tone.extension)
  assert.equal(await service.dataUrl(tone.id, tone.extension), null)
  await assert.rejects(service.dataUrl('..\\outside', '.wav'), /invalid/)
})

test('rejects ringtone files with a mismatched signature', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'mydesk-alarm-invalid-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const source = path.join(directory, 'not-audio.wav')
  await fs.writeFile(source, 'not a wav file')
  const service = new AlarmToneService(path.join(directory, 'managed'))
  await assert.rejects(service.store(source), /valid supported audio/)
})
